def test_final_food_row_beyond_weekday_label_merge_is_not_omitted():
    # The label ends at row 4, but food continues through row 5 before footer.
    cells=[CellData('B1',1,2,'아침','아침'),
           CellData('A2',2,1,'토','토',merged_range='A2:A4'),
           CellData('B2',2,2,'국','국'), CellData('B3',3,2,'달걀','달걀'),
           CellData('B4',4,2,'김치','김치'), CellData('B5',5,2,'채소샐러드','채소샐러드'),
           CellData('A6',6,1,'간식 안내','간식 안내',merged_range='A6:B6')]
    sheet=SheetGrid('S',1,6,1,2,[],cells)
    profile=LayoutProfile('weekday_blocks_meal_columns','high',[],'S',{'breakfast':'B1'})
    records=extract_records(sheet,profile,{'institution_id':'I'},'xlsx',2025,8)
    assert records
    assert all([i.name for i in r.menu_items]==['국','달걀','김치','채소샐러드'] for r in records)
    assert all(r.source['cells']==['B2','B3','B4','B5'] for r in records)

