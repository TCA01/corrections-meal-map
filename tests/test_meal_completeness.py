def test_source_range_missing_food_forces_review():
    cells=[CellData('B2',2,2,'국','국'),CellData('B3',3,2,'김치','김치')]
    sheet=SheetGrid('S',2,3,2,2,[],cells)
    record=MealRecord('I','2026-01-01','breakfast',[MenuItem('김치','김치')],
                      {'cells':['B3'],'block_bounds':[2,3,2,2]}, {})
    coverage=source_coverage([record],sheet)
    assert not coverage['source_completeness_valid']
    assert coverage['issues'][0]['code']=='INCOMPLETE_SOURCE_RANGE'
    assert coverage['issues'][0]['missing_cells']==['B2']

