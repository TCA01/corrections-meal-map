ROOT=Path(__file__).resolve().parents[1]
FIXTURE=ROOT/'tests/fixtures/completeness'
MANIFEST=json.loads((FIXTURE/'manifest.json').read_text(encoding='utf-8'))
GOLDEN=json.loads((FIXTURE/'golden.json').read_text(encoding='utf-8'))['slots']

@pytest.fixture(scope='module')
def results():
    return {m['document_id']:ExcelMealParser(ROOT).parse_sample(m) for m in MANIFEST}

def test_full_meal_goldens_match_source_cells_independently():
    for item in MANIFEST:
        workbook=read_workbook(ROOT/item['local_path'])
        for slot in [s for s in GOLDEN if s['document_id']==item['document_id']]:
            sheet=next(s for s in workbook.sheets if s.name==slot['sheet'])
            cells={c.coordinate:c for c in sheet.cells}
            # The expected list was hand transcribed, never generated by parser.
            actual=[i.name for address in slot['cells'] for i in split_menu_text(cells[address].text)]
            assert actual==slot['items']

